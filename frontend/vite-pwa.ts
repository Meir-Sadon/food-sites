import { existsSync, readFileSync } from 'node:fs'
import type { IncomingMessage, ServerResponse } from 'node:http'
import sharp from 'sharp'
import type { Plugin } from 'vite'

type Texts = { app?: { name?: string }; pwa?: { offlineTitle?: string; offlineText?: string } }

const readTexts = (path: string): Texts => (existsSync(path) ? (JSON.parse(readFileSync(path, 'utf8')) as Texts) : {})

/** A colour variable's value from theme.css when it is a plain colour (not var(...)), else the fallback. */
function themeColor(css: string, variable: string, fallback: string): string {
  const value = new RegExp(`${variable}\\s*:\\s*([^;]+);`).exec(css)?.[1].trim()
  return value && /^#[0-9a-f]{3,8}$/i.test(value) ? value : fallback
}

const esc = (text: string) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;')

/**
 * Makes each site installable as an app (PWA), from its own folder: name from i18n (`app.name`), colours from
 * theme.css (`--color-accent`, `--color-bg`) and icons drawn from `public/favicon.svg`. Emits `manifest.webmanifest`,
 * `icon-*.png`, `apple-touch-icon.png` and `sw.js`, and adds the matching tags to index.html. Nothing per business lives here.
 *
 * The service worker caches nothing: it only answers a failed page load with an offline notice, so API calls and
 * new deploys (new hashed bundles) always come straight from the network.
 */
export function sitePwa(siteDir: string, sharedTextsPath: string): Plugin {
  const texts = { ...readTexts(sharedTextsPath), ...readTexts(`${siteDir}/i18n/he.json`) }
  const shared = readTexts(sharedTextsPath)
  const name = texts.app?.name ?? shared.app?.name ?? ''
  const offlineTitle = readTexts(`${siteDir}/i18n/he.json`).pwa?.offlineTitle ?? shared.pwa?.offlineTitle ?? ''
  const offlineText = readTexts(`${siteDir}/i18n/he.json`).pwa?.offlineText ?? shared.pwa?.offlineText ?? ''
  const css = existsSync(`${siteDir}/theme.css`) ? readFileSync(`${siteDir}/theme.css`, 'utf8') : ''
  const accent = themeColor(css, '--color-accent', '#333333')
  const background = themeColor(css, '--color-bg', '#ffffff')
  const favicon = `${siteDir}/public/favicon.svg`

  const manifest = JSON.stringify({
    name,
    short_name: name.length > 12 ? name.slice(0, 12).trim() : name,
    lang: 'he',
    dir: 'rtl',
    start_url: '/?source=pwa',
    scope: '/',
    id: '/',
    display: 'standalone',
    background_color: background,
    theme_color: accent,
    icons: [
      { src: '/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: '/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
      { src: '/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ],
  })

  const sw = `// Generated by vite-pwa.ts. Caches nothing, so deploys and API calls are never stale.
self.addEventListener('install', () => self.skipWaiting())
self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()))
self.addEventListener('fetch', (event) => {
  if (event.request.mode !== 'navigate') return
  event.respondWith(
    fetch(event.request).catch(
      () =>
        new Response(
          ${JSON.stringify(
            `<!doctype html><html lang="he" dir="rtl"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${esc(name)}</title>` +
              `<body style="font-family:sans-serif;text-align:center;padding:3rem 1rem;background:${background}"><h1>${esc(offlineTitle)}</h1><p>${esc(offlineText)}</p>`,
          )},
          { status: 503, headers: { 'Content-Type': 'text/html; charset=utf-8' } },
        ),
    ),
  )
})
`

  async function icons(): Promise<Record<string, Buffer>> {
    if (!existsSync(favicon)) return {}
    const svg = readFileSync(favicon)
    const draw = (size: number) => sharp(svg, { density: Math.ceil((72 * size) / 32) }).resize(size, size).png().toBuffer()
    // On a solid square the picture keeps to the middle, inside the safe zone that maskable and iOS icons get cropped to.
    const onSquare = async (size: number, share: number) =>
      sharp({ create: { width: size, height: size, channels: 4, background: accent } })
        .composite([{ input: await draw(Math.round(size * share)), gravity: 'centre' }])
        .png()
        .toBuffer()
    return {
      'icon-192.png': await draw(192),
      'icon-512.png': await draw(512),
      'icon-maskable-512.png': await onSquare(512, 0.64),
      'apple-touch-icon.png': await onSquare(180, 0.8),
    }
  }

  const types: Record<string, string> = { '.png': 'image/png', '.webmanifest': 'application/manifest+json', '.js': 'text/javascript' }

  return {
    name: 'site-pwa',
    transformIndexHtml: () => [
      { tag: 'link', attrs: { rel: 'manifest', href: '/manifest.webmanifest' }, injectTo: 'head' },
      { tag: 'meta', attrs: { name: 'theme-color', content: accent }, injectTo: 'head' },
      { tag: 'link', attrs: { rel: 'apple-touch-icon', href: '/apple-touch-icon.png' }, injectTo: 'head' },
      { tag: 'meta', attrs: { name: 'mobile-web-app-capable', content: 'yes' }, injectTo: 'head' },
      { tag: 'meta', attrs: { name: 'apple-mobile-web-app-capable', content: 'yes' }, injectTo: 'head' },
      { tag: 'meta', attrs: { name: 'apple-mobile-web-app-title', content: name }, injectTo: 'head' },
      { tag: 'meta', attrs: { name: 'apple-mobile-web-app-status-bar-style', content: 'default' }, injectTo: 'head' },
    ],
    async generateBundle() {
      this.emitFile({ type: 'asset', fileName: 'manifest.webmanifest', source: manifest })
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: sw })
      for (const [fileName, source] of Object.entries(await icons())) this.emitFile({ type: 'asset', fileName, source })
    },
    configureServer(server) {
      server.middlewares.use(async (req: IncomingMessage, res: ServerResponse, next: () => void) => {
        const path = (req.url ?? '').split('?')[0]
        const files: Record<string, string | Buffer> = { '/manifest.webmanifest': manifest, '/sw.js': sw, ...Object.fromEntries(Object.entries(await icons()).map(([k, v]) => [`/${k}`, v])) }
        const body = files[path]
        if (body === undefined) return next()
        res.setHeader('Content-Type', types[path.slice(path.lastIndexOf('.'))] ?? 'application/octet-stream')
        res.end(body)
      })
    },
  }
}
